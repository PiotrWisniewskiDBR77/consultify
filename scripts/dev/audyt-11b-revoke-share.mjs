import { chromium } from 'playwright';
const AUTH = '/private/tmp/stanowisko-noc/auth-11b.json';
const BASE = 'http://127.0.0.1:3117';
const OUT_DIR = '/private/tmp/wt-11b/evidence/1-1-b';
const browser = await chromium.launch();
const ctx = await browser.newContext({ storageState: AUTH, viewport: { width: 1440, height: 900 } });
const page = await ctx.newPage();
await page.goto(`${BASE}/chat?workPanel=1`, { waitUntil: 'networkidle', timeout: 30000 });
await page.waitForTimeout(2500);
await page.locator('[aria-label="Udostępnij dokument Canvas"]').click();
await page.waitForTimeout(1000);
const netLog = [];
page.on('requestfinished', (req) => { if (req.url().includes('/api/')) netLog.push(req.url()); });
await page.getByText('Cofnij udostępnianie').click({ timeout: 5000 }).catch(e => console.log('revoke click failed', String(e).slice(0,200)));
await page.waitForTimeout(1000);
await page.screenshot({ path: `${OUT_DIR}/24-po-cofnieciu-udostepniania.png` });
console.log(JSON.stringify(netLog));
await browser.close();
