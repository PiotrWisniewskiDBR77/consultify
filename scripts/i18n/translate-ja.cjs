// Combined dictionary
const ALL_TRANSLATIONS = { ...TRANSLATIONS, ...MORE_TRANSLATIONS, ...PHRASE_TRANSLATIONS };

function translateText(text, locale = 'ja') {
  if (typeof text !== 'string') return text;
  
  // Remove [JA] or [TODO] prefix
  let cleanText = text.replace(/^\[(JA|TODO)\]\s*/, '');
  
  // Check exact match in all dictionaries
  if (ALL_TRANSLATIONS[cleanText]) {
    return ALL_TRANSLATIONS[cleanText];
  }
  
  // Try word-by-word translation for compound phrases
  let translated = cleanText;
  
  // Sort by length (longer phrases first) to avoid partial replacements
  const sortedPhrases = Object.entries(ALL_TRANSLATIONS)
    .sort((a, b) => b[0].length - a[0].length);
  
  for (const [eng, jap] of sortedPhrases) {
    if (translated.includes(eng)) {
      translated = translated.split(eng).join(jap);
    }
  }
  
  // If we made any changes, return the result
  if (translated !== cleanText) {
    // Check if there are still significant English words (4+ chars)
    const englishWords = translated.match(/[a-zA-Z]{4,}/g) || [];
    if (englishWords.length === 0) {
      return translated;
    }
    // If only a few English words remain, it's probably OK (technical terms)
    if (englishWords.length <= 2) {
      return translated;
    }
  }
  
  // Return with [JA] prefix for manual review
  return `[JA] ${cleanText}`;
}

function processObject(obj, path = '') {
  if (typeof obj === 'string') {
    if (obj.startsWith('[JA]') || obj.startsWith('[TODO]')) {
      return translateText(obj);
    }
    return obj;
  }
  
  if (Array.isArray(obj)) {
    return obj.map((item, i) => processObject(item, `${path}[${i}]`));
  }
  
  if (typeof obj === 'object' && obj !== null) {
    const result = {};
    for (const [key, value] of Object.entries(obj)) {
      result[key] = processObject(value, `${path}.${key}`);
    }
    return result;
  }
  
  return obj;
}

function main() {
  const localesDir = path.join(__dirname, '../../public/locales/ja');
  const files = ['translation.json', 'assessment-module.json', 'discovery.json'];
  
  console.log('🇯🇵 Japanese Translation Script');
  console.log('================================\n');
  
  let totalTranslated = 0;
  let totalRemaining = 0;
  
  for (const file of files) {
    const filePath = path.join(localesDir, file);
    
    if (!fs.existsSync(filePath)) {
      console.log(`⚠️ File not found: ${file}`);
      continue;
    }
    
    console.log(`Processing ${file}...`);
    
    const content = JSON.parse(fs.readFileSync(filePath, 'utf-8'));
    const contentStr = JSON.stringify(content);
    
    // Count before
    const beforeJA = (contentStr.match(/\[JA\]/g) || []).length;
    const beforeTODO = (contentStr.match(/\[TODO\]/g) || []).length;
    const totalBefore = beforeJA + beforeTODO;
    
    // Process
    const processed = processObject(content);
    const processedStr = JSON.stringify(processed, null, 2);
    
    // Count after
    const afterJA = (processedStr.match(/\[JA\]/g) || []).length;
    const afterTODO = (processedStr.match(/\[TODO\]/g) || []).length;
    const totalAfter = afterJA + afterTODO;
    
    const translated = totalBefore - totalAfter;
    totalTranslated += translated;
    totalRemaining += totalAfter;
    
    // Save
    fs.writeFileSync(filePath, processedStr + '\n', 'utf-8');
    
    console.log(`  ✓ Translated: ${translated} strings`);
    console.log(`  ⚠ Remaining: ${totalAfter} strings\n`);
  }
  
  console.log('================================');
  console.log(`Total translated: ${totalTranslated}`);
  console.log(`Total remaining: ${totalRemaining}`);
  console.log('\nDone! Run again after adding more translations to the dictionary.');
}

main();
