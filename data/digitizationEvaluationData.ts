export const getAxisById = (id: string): DigitizationAxis | undefined => 
    DIGITIZATION_AXES.find(axis => axis.id === id);

export const getAreaByCode = (code: string): { axis: DigitizationAxis; area: EvaluationArea } | undefined => {
    for (const axis of DIGITIZATION_AXES) {
        const area = axis.areas.find(a => a.code === code);
        if (area) return { axis, area };
    }
    return undefined;
};

export const getTotalAreas = (): number => 
    DIGITIZATION_AXES.reduce((sum, axis) => sum + axis.areas.length, 0);

export const getLevelColor = (level: number): string => {
    const colors = ['#ef4444', '#f97316', '#f59e0b', '#eab308', '#84cc16', '#22c55e', '#10b981'];
    return colors[Math.min(level - 1, colors.length - 1)] || '#64748b';
};

export const calculateAxisScore = (areaScores: Record<string, { currentLevel: number }>): number => {
    const scores = Object.values(areaScores);
    if (scores.length === 0) return 0;
    return scores.reduce((sum, s) => sum + s.currentLevel, 0) / scores.length;
};

