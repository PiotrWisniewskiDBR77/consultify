const Section: React.FC<{ label: string; children: React.ReactNode }> = ({ label, children }) => (
  <div>
    <div className="text-[10px] uppercase tracking-wider text-slate-400 dark:text-slate-500 mb-1.5 font-medium">{label}</div>
    {children}
  </div>
);

const ExportCard: React.FC<{
  icon: React.ReactNode;
  title: string;
  description: string;
  action: string;
  onAction: () => void;
  loading?: boolean;
}> = ({ icon, title, description, action, onAction, loading }) => (
  <div className="rounded-xl border border-slate-200 dark:border-navy-700 bg-white dark:bg-navy-900 p-4">
    <div className="flex items-start gap-3">
      <div className="shrink-0 w-10 h-10 flex items-center justify-center rounded-xl bg-slate-100 dark:bg-navy-800">
        {icon}
      </div>
      <div className="flex-1 min-w-0">
        <div className="text-sm font-medium text-slate-900 dark:text-white">{title}</div>
        <p className="text-[11px] text-slate-500 dark:text-slate-400 mt-0.5 leading-relaxed">{description}</p>
        <button
          type="button"
          onClick={onAction}
          disabled={loading}
          className="mt-2.5 h-7 px-3 rounded-lg text-[11px] font-medium bg-slate-100 dark:bg-navy-800 text-slate-700 dark:text-slate-300 hover:bg-slate-200 dark:hover:bg-navy-700 transition-colors flex items-center gap-1.5 disabled:opacity-50"
        >
          {loading ? <Loader2 size={10} className="animate-spin" /> : <ChevronRight size={10} />}
          {action}
        </button>
      </div>
    </div>
  </div>
);
