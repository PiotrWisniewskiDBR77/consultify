export const ReportCompactPanel: React.FC<ReportCompactPanelProps> = ({
  report,
  isOpen,
  onClose,
  onGenerate,
  mode = 'overlay',
}) => {
  const { t } = useTranslation();
  const [activeTab, setActiveTab] = useState<PanelTab>('contract');
  const [isExporting, setIsExporting] = useState(false);
  const panelRef = useRef<HTMLDivElement>(null);

  const rag = useMemo(() => (report ? computeRAG(report) : 'green'), [report]);
  const ragConf = RAG_CONFIG[rag];

  const handleCopyMarkdown = useCallback(() => {
    if (!report) return;
    const md = buildReportMarkdown(report, rag);
    navigator.clipboard.writeText(md).then(
      () => toast.success(t('execution.reportPanel.copied', 'Report copied to clipboard')),
      () => toast.error(t('execution.reportPanel.copyFailed', 'Copy failed'))
    );
  }, [report, rag, t]);

  const handleExportPDF = useCallback(() => {
    if (!report) return;
    setIsExporting(true);
    try {
      exportReportPDF(report, rag);
      toast.success(t('execution.reportPanel.pdfExported', 'PDF downloaded'));
    } catch {
      toast.error(t('execution.reportPanel.pdfFailed', 'PDF export failed'));
    } finally {
      setIsExporting(false);
    }
  }, [report, rag, t]);

  const handleExportPresentation = useCallback(() => {
    if (!report) return;
    const md = buildReportMarkdown(report, rag);
    const encoded = encodeURIComponent(md);
    const title = encodeURIComponent(report.title);
    window.open(`/prezentacje?sourceType=execution_report&sourceName=${title}&content=${encoded}`, '_blank');
    toast.success(t('execution.reportPanel.presentationOpened', 'Opening presentation generator…'));
  }, [report, rag, t]);

  if (!isOpen || !report) return null;

  const RagIcon = ragConf.icon;

  return (
    <AnimatePresence>
      {isOpen && (
        <>
          {mode === 'overlay' && (
            <motion.div
              initial={{ opacity: 0 }}
              animate={{ opacity: 1 }}
              exit={{ opacity: 0 }}
              className="fixed inset-0 bg-black/20 dark:bg-black/40 z-40"
              onClick={onClose}
            />
          )}
          <motion.div
            ref={panelRef}
            initial={{ x: '100%' }}
            animate={{ x: 0 }}
            exit={{ x: '100%' }}
            transition={{ type: 'spring', damping: 30, stiffness: 300 }}
            className="fixed right-0 top-0 bottom-0 w-[440px] max-w-full z-50 flex flex-col bg-white dark:bg-navy-950 border-l border-slate-200 dark:border-navy-700 shadow-2xl"
          >
            {/* RAG status bar */}
            <div className={`h-1.5 w-full ${rag === 'green' ? 'bg-emerald-500' : rag === 'amber' ? 'bg-amber-500' : 'bg-rose-500'}`} />

            {/* Header */}
            <div className="px-4 pt-3 pb-2 border-b border-slate-100 dark:border-navy-800">
              <div className="flex items-start justify-between gap-3">
                <div className="min-w-0 flex-1">
                  <div className="flex items-center gap-2 mb-1">
                    <div className={`px-2 py-0.5 rounded text-[10px] font-semibold uppercase tracking-wide ${ragConf.bg} ${ragConf.text} ${ragConf.border} border`}>
                      <RagIcon size={10} className="inline mr-1 -mt-0.5" />
                      {ragConf.label}
                    </div>
                    <span className="text-[10px] font-medium uppercase tracking-wide text-slate-400 dark:text-slate-500">
                      {report.cadence}
                    </span>
                  </div>
                  <h3 className="text-sm font-semibold text-slate-900 dark:text-white truncate">
                    {report.title}
                  </h3>
                  <p className="text-[11px] text-slate-500 dark:text-slate-400 truncate mt-0.5">
                    {report.audience}
                  </p>
                </div>
                <div className="flex items-center gap-1 shrink-0">
                  {onGenerate && (
                    <button
                      type="button"
                      onClick={() => onGenerate(report)}
                      className="p-1.5 rounded-lg text-slate-400 hover:text-cyan-500 hover:bg-slate-100 dark:hover:bg-navy-800 transition-colors"
                      title={t('execution.reportPanel.generate', 'Generate with AI')}
                    >
                      <Maximize2 size={14} />
                    </button>
                  )}
                  <button
                    type="button"
                    onClick={onClose}
                    className="p-1.5 rounded-lg text-slate-400 hover:text-slate-600 hover:bg-slate-100 dark:hover:bg-navy-800 transition-colors"
                  >
                    <X size={14} />
                  </button>
                </div>
              </div>

              {/* Live highlights */}
              <div className="flex flex-wrap gap-1.5 mt-2.5">
                {report.highlights.map((h) => (
                  <span
                    key={h.label}
                    className={`inline-flex items-center gap-0.5 px-2 py-0.5 rounded text-[10px] font-medium ${
                      h.variant === 'critical'
                        ? 'bg-rose-50 dark:bg-rose-900/20 text-rose-600 dark:text-rose-400'
                        : h.variant === 'warn'
                          ? 'bg-amber-50 dark:bg-amber-900/20 text-amber-600 dark:text-amber-400'
                          : 'bg-slate-100 dark:bg-navy-800 text-slate-600 dark:text-slate-400'
                    }`}
                  >
                    {h.label}: {h.value}
                  </span>
                ))}
              </div>

              {/* Tabs */}
              <div className="flex gap-0.5 mt-3 -mb-px">
                {PANEL_TABS.map((tab) => {
                  const Icon = tab.icon;
                  const isActive = activeTab === tab.id;
                  return (
                    <button
                      key={tab.id}
                      type="button"
                      onClick={() => setActiveTab(tab.id)}
                      className={`flex items-center gap-1 px-2.5 py-1.5 text-[11px] font-medium rounded-t-lg border-b-2 transition-colors ${
                        isActive
                          ? 'border-cyan-500 text-cyan-600 dark:text-cyan-400 bg-cyan-50/50 dark:bg-cyan-900/10'
                          : 'border-transparent text-slate-400 dark:text-slate-500 hover:text-slate-600 dark:hover:text-slate-300'
                      }`}
                    >
                      <Icon size={12} />
                      {t(tab.labelKey, tab.id)}
                    </button>
                  );
                })}
              </div>
            </div>

            {/* Body */}
            <div className="flex-1 overflow-y-auto p-4 space-y-4">
              {activeTab === 'contract' && (
                <>
                  <Section label="Scope">
                    <p className="text-xs text-slate-700 dark:text-slate-300 leading-relaxed">{report.scope}</p>
                  </Section>

                  <Section label="Data Sources">
                    <div className="flex flex-wrap gap-1">
                      {report.dataSources.map((ds) => (
                        <span key={ds} className="inline-block px-1.5 py-0.5 rounded bg-slate-100 dark:bg-navy-800 text-[10px] text-slate-600 dark:text-slate-400">{ds}</span>
                      ))}
                    </div>
                  </Section>

                  <Section label="Mandatory Sections">
                    <ol className="space-y-1 list-decimal list-inside">
                      {report.sections.map((s) => (
                        <li key={s} className="text-[11px] text-slate-600 dark:text-slate-400">{s}</li>
                      ))}
                    </ol>
                  </Section>

                  <Section label="RAG / Confidence Logic">
                    <p className="text-[11px] text-slate-600 dark:text-slate-400 leading-relaxed">{report.ragLogic}</p>
                  </Section>

                  <Section label="Expected Follow-up Actions">
                    <div className="flex flex-wrap gap-1.5">
                      {report.followUpActions.map((a) => (
                        <span key={a} className="inline-block px-2 py-0.5 rounded-full bg-cyan-50 dark:bg-cyan-900/20 text-[10px] font-medium text-cyan-700 dark:text-cyan-300">{a}</span>
                      ))}
                    </div>
                  </Section>
                </>
              )}

              {activeTab === 'data' && (
                <>
                  <div className={`rounded-xl p-4 ${ragConf.bg} ${ragConf.border} border`}>
                    <div className="flex items-center gap-2 mb-2">
                      <RagIcon size={16} className={ragConf.text} />
                      <span className={`text-sm font-semibold ${ragConf.text}`}>{ragConf.label}</span>
                    </div>
                    <p className="text-[11px] text-slate-600 dark:text-slate-400 leading-relaxed">{report.ragLogic}</p>
                  </div>

                  <Section label="Live Metrics">
                    <div className="space-y-2">
                      {report.highlights.map((h) => (
                        <div key={h.label} className="flex items-center justify-between py-1.5 border-b border-slate-100 dark:border-navy-800 last:border-0">
                          <span className="text-xs text-slate-500 dark:text-slate-400">{h.label}</span>
                          <span className={`text-sm font-semibold tabular-nums ${
                            h.variant === 'critical' ? 'text-rose-600 dark:text-rose-400' :
                            h.variant === 'warn' ? 'text-amber-600 dark:text-amber-400' :
                            'text-slate-900 dark:text-white'
                          }`}>
                            {h.value}
                          </span>
                        </div>
                      ))}
                    </div>
                  </Section>

                  <Section label="Data Sources">
                    <div className="space-y-1">
                      {report.dataSources.map((ds) => (
                        <div key={ds} className="flex items-center gap-2 text-xs text-slate-600 dark:text-slate-400">
                          <CheckCircle2 size={10} className="text-emerald-500 shrink-0" />
                          {ds}
                        </div>
                      ))}
                    </div>
                  </Section>
                </>
              )}

              {activeTab === 'export' && (
                <>
                  <ExportCard
                    icon={<FileText size={20} className="text-cyan-500" />}
                    title={t('execution.reportPanel.exportPdf', 'Export as PDF Report')}
                    description={t('execution.reportPanel.exportPdfDesc', 'A4 report with RAG header, live data, sections, and follow-up checklist. Ready for stakeholder distribution.')}
                    action={t('execution.reportPanel.downloadPdf', 'Download PDF')}
                    onAction={handleExportPDF}
                    loading={isExporting}
                  />

                  <ExportCard
                    icon={<Presentation size={20} className="text-purple-500" />}
                    title={t('execution.reportPanel.exportPresentation', 'Create Presentation')}
                    description={t('execution.reportPanel.exportPresentationDesc', 'Open in Presentation Generator to create a slide deck from this report definition and live data.')}
                    action={t('execution.reportPanel.openGenerator', 'Open Generator')}
                    onAction={handleExportPresentation}
                  />

                  <ExportCard
                    icon={<Copy size={20} className="text-slate-500 dark:text-slate-400" />}
                    title={t('execution.reportPanel.copyMarkdown', 'Copy as Markdown')}
                    description={t('execution.reportPanel.copyMarkdownDesc', 'Full report definition with live data in markdown format. Paste into documents, wikis, or chat.')}
                    action={t('execution.reportPanel.copy', 'Copy to Clipboard')}
                    onAction={handleCopyMarkdown}
                  />
                </>
              )}
            </div>

            {/* Footer */}
            <div className="px-4 py-3 border-t border-slate-100 dark:border-navy-800 flex items-center gap-2">
              {onGenerate && (
                <button
                  type="button"
                  onClick={() => onGenerate(report)}
                  className="h-8 px-4 rounded-lg text-xs font-medium bg-cyan-600 text-white hover:bg-cyan-700 transition-colors flex items-center gap-1.5"
                >
                  <Sparkles size={12} />
                  {t('execution.reportPanel.generateAI', 'Generate with AI')}
                </button>
              )}
              <button
                type="button"
                onClick={handleExportPDF}
                disabled={isExporting}
                className="h-8 px-3 rounded-lg text-xs font-medium border border-slate-200 dark:border-navy-700 text-slate-600 dark:text-slate-400 hover:bg-slate-50 dark:hover:bg-navy-800 transition-colors flex items-center gap-1.5 disabled:opacity-50"
              >
                {isExporting ? <Loader2 size={12} className="animate-spin" /> : <Download size={12} />}
                PDF
              </button>
              <button
                type="button"
                onClick={handleCopyMarkdown}
                className="h-8 px-3 rounded-lg text-xs font-medium border border-slate-200 dark:border-navy-700 text-slate-600 dark:text-slate-400 hover:bg-slate-50 dark:hover:bg-navy-800 transition-colors flex items-center gap-1.5"
              >
                <Copy size={12} />
                {t('execution.reportPanel.copy', 'Copy')}
              </button>
            </div>
          </motion.div>
        </>
      )}
    </AnimatePresence>
  );
};

