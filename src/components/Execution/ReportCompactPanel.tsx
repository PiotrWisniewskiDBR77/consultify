function buildReportMarkdown(report: ReportDef, rag: 'green' | 'amber' | 'red'): string {
  const ragLabel = RAG_CONFIG[rag].label;
  const now = new Date().toLocaleDateString('en-GB', { day: '2-digit', month: 'short', year: 'numeric' });
  return [
    `# ${report.title}`,
    `**Status: ${ragLabel.toUpperCase()}** · Generated: ${now}`,
    `**Audience:** ${report.audience} · **Cadence:** ${report.cadence}`,
    '',
    `## Scope`,
    report.scope,
    '',
    `## Live Data`,
    ...report.highlights.map((h) => `- **${h.label}:** ${h.value}${h.variant === 'critical' ? ' ⚠️' : h.variant === 'warn' ? ' ⚡' : ''}`),
    '',
    `## Data Sources`,
    ...report.dataSources.map((d) => `- ${d}`),
    '',
    `## Report Sections`,
    ...report.sections.map((s, i) => `${i + 1}. ${s}`),
    '',
    `## RAG / Confidence Logic`,
    report.ragLogic,
    '',
    `## Expected Follow-up Actions`,
    ...report.followUpActions.map((a) => `- [ ] ${a}`),
    '',
    `---`,
    `_Generated by Consultify Execution Reports_`,
  ].join('\n');
}

function exportReportPDF(report: ReportDef, rag: 'green' | 'amber' | 'red') {
  const pdf = new jsPDF({ orientation: 'portrait', unit: 'mm', format: 'a4' });
  const pageW = pdf.internal.pageSize.getWidth();
  const pageH = pdf.internal.pageSize.getHeight();
  const m = 15;
  const maxW = pageW - m * 2;
  let y = m;

  const addPage = (need: number) => {
    if (y + need > pageH - m) { pdf.addPage(); y = m; }
  };

  const ragConf = RAG_CONFIG[rag];
  const ragColors: Record<string, [number, number, number]> = {
    green: [16, 185, 129],
    amber: [245, 158, 11],
    red: [239, 68, 68],
  };

  // Header bar
  const barColor = ragColors[rag];
  pdf.setFillColor(...barColor);
  pdf.rect(0, 0, pageW, 12, 'F');
  pdf.setFontSize(9);
  pdf.setTextColor(255, 255, 255);
  pdf.text(ragConf.label.toUpperCase(), m, 8);
  pdf.text(new Date().toLocaleDateString(), pageW - m, 8, { align: 'right' });
  y = 20;

  // Title
  pdf.setFontSize(18);
  pdf.setTextColor(20, 30, 70);
  pdf.text(report.title, m, y);
  y += 8;

  pdf.setFontSize(10);
  pdf.setTextColor(100, 100, 100);
  pdf.text(`${report.audience} · ${report.cadence}`, m, y);
  y += 10;

  // Live data highlights
  pdf.setFontSize(11);
  pdf.setTextColor(30, 30, 30);
  pdf.text('Live Data', m, y);
  y += 6;
  for (const h of report.highlights) {
    addPage(6);
    const isAlert = h.variant === 'critical' || h.variant === 'warn';
    pdf.setFontSize(9);
    pdf.setTextColor(isAlert ? ragColors[h.variant === 'critical' ? 'red' : 'amber'][0] : 80,
      isAlert ? ragColors[h.variant === 'critical' ? 'red' : 'amber'][1] : 80,
      isAlert ? ragColors[h.variant === 'critical' ? 'red' : 'amber'][2] : 80);
    pdf.text(`${h.label}: ${h.value}`, m + 2, y);
    y += 5;
  }
  y += 4;

  // Scope
  addPage(12);
  pdf.setFontSize(11);
  pdf.setTextColor(30, 30, 30);
  pdf.text('Scope', m, y);
  y += 5;
  pdf.setFontSize(9);
  pdf.setTextColor(60, 60, 60);
  const scopeLines = pdf.splitTextToSize(report.scope, maxW);
  for (const line of scopeLines) { addPage(5); pdf.text(line, m + 2, y); y += 4.5; }
  y += 4;

  // Sections
  addPage(12);
  pdf.setFontSize(11);
  pdf.setTextColor(30, 30, 30);
  pdf.text('Report Sections', m, y);
  y += 5;
  pdf.setFontSize(9);
  pdf.setTextColor(60, 60, 60);
  report.sections.forEach((s, i) => { addPage(5); pdf.text(`${i + 1}. ${s}`, m + 2, y); y += 4.5; });
  y += 4;

  // RAG logic
  addPage(12);
  pdf.setFontSize(11);
  pdf.setTextColor(30, 30, 30);
  pdf.text('RAG / Confidence Logic', m, y);
  y += 5;
  pdf.setFontSize(9);
  pdf.setTextColor(60, 60, 60);
  const ragLines = pdf.splitTextToSize(report.ragLogic, maxW);
  for (const line of ragLines) { addPage(5); pdf.text(line, m + 2, y); y += 4.5; }
  y += 4;

  // Follow-up actions
  addPage(12);
  pdf.setFontSize(11);
  pdf.setTextColor(30, 30, 30);
  pdf.text('Expected Follow-up Actions', m, y);
  y += 5;
  pdf.setFontSize(9);
  pdf.setTextColor(60, 60, 60);
  report.followUpActions.forEach((a) => { addPage(5); pdf.text(`☐ ${a}`, m + 2, y); y += 4.5; });

  // Footer
  const totalPages = pdf.internal.pages.length - 1;
  for (let i = 1; i <= totalPages; i++) {
    pdf.setPage(i);
    pdf.setFontSize(8);
    pdf.setTextColor(150, 150, 150);
    pdf.text(`Page ${i}/${totalPages} · Consultify Execution Reports`, pageW - m, pageH - 5, { align: 'right' });
  }

  const slug = report.title.toLowerCase().replace(/[^a-z0-9]+/g, '-').slice(0, 40);
  pdf.save(`${slug}-${new Date().toISOString().slice(0, 10)}.pdf`);
}

