/**
 * ReportCompactPanel
 *
 * Side panel (menu 3) for execution report quick view.
 * Shows RAG status header, report contract, live highlights,
 * and export actions (PDF report / PPTX presentation).
 */

import { AnimatePresence, motion } from 'framer-motion';
import {
  AlertTriangle,
  CheckCircle2,
  ChevronRight,
  Clock,
  Copy,
  Download,
  FileText,
  Loader2,
  Maximize2,
  Presentation,
  Sparkles,
  X,
} from 'lucide-react';
import React, { useCallback, useMemo, useRef, useState } from 'react';
import toast from 'react-hot-toast';
import { useTranslation } from 'react-i18next';
import jsPDF from 'jspdf';

// ---------------------------------------------------------------------------
// TYPES
// ---------------------------------------------------------------------------

export interface ReportHighlight {
  label: string;
  value: string | number;
  variant?: 'default' | 'warn' | 'critical';
}

export interface ReportDef {
  id: string;
  title: string;
  audience: string;
  cadence: string;
  scope: string;
  dataSources: string[];
  sections: string[];
  ragLogic: string;
  followUpActions: string[];
  icon: React.ReactNode;
  highlights: ReportHighlight[];
}

interface ReportCompactPanelProps {
  report: ReportDef | null;
  isOpen: boolean;
  onClose: () => void;
  onGenerate?: (report: ReportDef) => void;
  mode?: 'overlay' | 'embedded';
}

type PanelTab = 'contract' | 'data' | 'export';

// ---------------------------------------------------------------------------
// RAG LOGIC
// ---------------------------------------------------------------------------

function computeRAG(report: ReportDef): 'green' | 'amber' | 'red' {
  const crits = report.highlights.filter((h) => h.variant === 'critical');
  const warns = report.highlights.filter((h) => h.variant === 'warn');
  if (crits.length >= 2) return 'red';
  if (crits.length >= 1 || warns.length >= 2) return 'amber';
  return 'green';
}

const RAG_CONFIG = {
  green: {
    bg: 'bg-emerald-500/10',
    border: 'border-emerald-500/30',
    text: 'text-emerald-600 dark:text-emerald-400',
    label: 'On Track',
    icon: CheckCircle2,
  },
  amber: {
    bg: 'bg-amber-500/10',
    border: 'border-amber-500/30',
    text: 'text-amber-600 dark:text-amber-400',
    label: 'Needs Attention',
    icon: AlertTriangle,
  },
  red: {
    bg: 'bg-rose-500/10',
    border: 'border-rose-500/30',
    text: 'text-rose-600 dark:text-rose-400',
    label: 'At Risk',
    icon: AlertTriangle,
  },
} as const;

const PANEL_TABS: { id: PanelTab; labelKey: string; icon: React.ElementType }[] = [
  { id: 'contract', labelKey: 'execution.reportPanel.contract', icon: FileText },
  { id: 'data', labelKey: 'execution.reportPanel.data', icon: Sparkles },
  { id: 'export', labelKey: 'execution.reportPanel.export', icon: Download },
];

