const ReportEmailService = {
    /**
     * Get SMTP transporter configuration
     */
    getTransporter: async () => {
        const settings = await new Promise((resolve) => {
            db.all("SELECT key, value FROM settings WHERE key LIKE 'smtp_%'", [], (err, rows) => {
                if (err || !rows) return resolve({});
                const s = {};
                rows.forEach(r => s[r.key] = r.value);
                resolve(s);
            });
        });

        const smtpConfig = {
            host: settings['smtp_host'] || process.env.SMTP_HOST,
            port: parseInt(settings['smtp_port'] || process.env.SMTP_PORT || '587'),
            secure: (settings['smtp_port'] || process.env.SMTP_PORT) === '465',
            auth: {
                user: settings['smtp_user'] || process.env.SMTP_USER,
                pass: settings['smtp_pass'] || process.env.SMTP_PASS
            }
        };

        const fromAddress = settings['smtp_from'] || process.env.SMTP_FROM || '"Consultify Reports" <reports@consultify.com>';

        if (!smtpConfig.host || !smtpConfig.auth.user) {
            console.log('[ReportEmail] SMTP not configured, emails will be logged only');
            return { transporter: null, from: fromAddress };
        }

        return {
            transporter: nodemailer.createTransport(smtpConfig),
            from: fromAddress
        };
    },

    /**
     * Send a management report to recipients
     * @param {string} reportId - Report ID to send
     * @param {string[]} recipients - Array of email addresses
     * @param {object} options - Additional options
     * @returns {Promise<object>} Result with success status
     */
    sendReport: async (reportId, recipients, options = {}) => {
        if (!reportId || !recipients || recipients.length === 0) {
            throw new Error('Report ID and at least one recipient required');
        }

        console.log(`[ReportEmail] Sending report ${reportId} to ${recipients.length} recipient(s)`);

        // Get report data
        const report = await ManagementReportsService.getReport(reportId);
        if (!report) {
            throw new Error('Report not found');
        }

        // Parse content if it's a string
        if (typeof report.content === 'string') {
            try {
                report.content = JSON.parse(report.content);
            } catch (e) {
                console.warn('[ReportEmail] Could not parse report content');
            }
        }

        // Generate PDF if not exists
        let pdfPath = report.pdf_path;
        if (!pdfPath || options.regeneratePdf) {
            const pdfGenerator = getPdfGenerator();
            if (pdfGenerator && pdfGenerator.generateManagementReportPDF) {
                try {
                    pdfPath = await pdfGenerator.generateManagementReportPDF(report, options.branding || {});
                    console.log(`[ReportEmail] Generated PDF: ${pdfPath}`);
                } catch (pdfErr) {
                    console.error('[ReportEmail] PDF generation failed:', pdfErr.message);
                }
            }
        }

        // Get email template
        const template = EmailTemplates[report.report_type] || EmailTemplates.TEAM_MEETING;
        const subject = template.subject(report);
        const html = template.html(report, options.shareUrl);

        // Prepare attachments
        const attachments = [];
        if (pdfPath) {
            const absolutePath = path.isAbsolute(pdfPath) ? pdfPath : path.join(__dirname, '../../', pdfPath);
            if (fs.existsSync(absolutePath)) {
                attachments.push({
                    filename: `${report.title.replace(/[^a-zA-Z0-9]/g, '_')}_${report.period_end}.pdf`,
                    path: absolutePath,
                    contentType: 'application/pdf'
                });
            }
        }

        // Get transporter
        const { transporter, from } = await ReportEmailService.getTransporter();

        // Send to each recipient
        const results = [];
        for (const to of recipients) {
            try {
                if (transporter) {
                    await transporter.sendMail({
                        from,
                        to,
                        subject,
                        html,
                        attachments
                    });
                    console.log(`[ReportEmail] Sent to ${to}`);
                    results.push({ email: to, success: true });
                } else {
                    // Log-only mode
                    console.log(`[ReportEmail] Would send to ${to}:`);
                    console.log(`  Subject: ${subject}`);
                    console.log(`  Attachments: ${attachments.length}`);
                    results.push({ email: to, success: true, mock: true });
                }
            } catch (err) {
                console.error(`[ReportEmail] Failed to send to ${to}:`, err.message);
                results.push({ email: to, success: false, error: err.message });
            }
        }

        // Log the send action
        await ReportEmailService._logEmailSent(reportId, recipients, results);

        return {
            success: results.every(r => r.success),
            results,
            pdfPath
        };
    },

    /**
     * Send report to all saved recipients
     * @param {string} reportId - Report ID
     * @param {object} options - Options
     */
    sendToRecipients: async (reportId, options = {}) => {
        // Get recipients from database
        const recipients = await new Promise((resolve, reject) => {
            db.all(
                `SELECT u.email FROM management_report_recipients rr
                 JOIN users u ON rr.user_id = u.id
                 WHERE rr.report_id = ?`,
                [reportId],
                (err, rows) => {
                    if (err) return reject(err);
                    resolve(rows.map(r => r.email));
                }
            );
        });

        if (recipients.length === 0) {
            console.log('[ReportEmail] No recipients configured for report');
            return { success: true, results: [], message: 'No recipients configured' };
        }

        return ReportEmailService.sendReport(reportId, recipients, options);
    },

    /**
     * Schedule a report email for later
     * @param {string} reportId - Report ID
     * @param {string[]} recipients - Recipients
     * @param {Date} scheduledTime - When to send
     */
    scheduleEmail: async (reportId, recipients, scheduledTime) => {
        const scheduleId = require('uuid').v4();
        
        await new Promise((resolve, reject) => {
            db.run(
                `INSERT INTO scheduled_emails (id, report_id, recipients, scheduled_time, status)
                 VALUES (?, ?, ?, ?, 'PENDING')`,
                [scheduleId, reportId, JSON.stringify(recipients), scheduledTime.toISOString()],
                (err) => err ? reject(err) : resolve()
            );
        });

        console.log(`[ReportEmail] Scheduled email ${scheduleId} for ${scheduledTime.toISOString()}`);
        return scheduleId;
    },

    /**
     * Process scheduled emails (called by cron)
     */
    processScheduledEmails: async () => {
        const now = new Date().toISOString();
        
        const pending = await new Promise((resolve, reject) => {
            db.all(
                `SELECT * FROM scheduled_emails 
                 WHERE status = 'PENDING' AND scheduled_time <= ?`,
                [now],
                (err, rows) => err ? reject(err) : resolve(rows || [])
            );
        });

        console.log(`[ReportEmail] Processing ${pending.length} scheduled emails`);

        for (const email of pending) {
            try {
                const recipients = JSON.parse(email.recipients);
                await ReportEmailService.sendReport(email.report_id, recipients);
                
                await new Promise((resolve, reject) => {
                    db.run(
                        `UPDATE scheduled_emails SET status = 'SENT', sent_at = CURRENT_TIMESTAMP WHERE id = ?`,
                        [email.id],
                        (err) => err ? reject(err) : resolve()
                    );
                });
            } catch (err) {
                console.error(`[ReportEmail] Failed to process scheduled email ${email.id}:`, err.message);
                await new Promise((resolve) => {
                    db.run(
                        `UPDATE scheduled_emails SET status = 'FAILED', error = ? WHERE id = ?`,
                        [err.message, email.id],
                        () => resolve()
                    );
                });
            }
        }

        return pending.length;
    },

    /**
     * Log email send action for audit
     */
    _logEmailSent: async (reportId, recipients, results) => {
        const logId = require('uuid').v4();
        await new Promise((resolve) => {
            db.run(
                `INSERT INTO email_log (id, report_id, recipients, results, sent_at)
                 VALUES (?, ?, ?, ?, CURRENT_TIMESTAMP)`,
                [logId, reportId, JSON.stringify(recipients), JSON.stringify(results)],
                () => resolve()
            );
        });
    }
};

export default ReportEmailService;






