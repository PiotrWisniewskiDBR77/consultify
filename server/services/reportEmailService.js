// Lazy load PDF generator to avoid circular dependencies
let PdfGeneratorService;
const getPdfGenerator = () => {
    if (!PdfGeneratorService) {
        try {
            PdfGeneratorService = require('./pdfGeneratorService');
        } catch (e) {
            console.warn('[ReportEmail] PDF Generator not available:', e.message);
        }
    }
    return PdfGeneratorService;
};

