/**
 * GET /api/public/report/:token/check-auth
 * Check if the current request has a valid auth token.
 * Used by the public view to conditionally show download buttons.
 */
router.get('/:token/check-auth', async (req: Request, res: Response) => {
  try {
    const authHeader = req.headers.authorization;
    if (!authHeader || !authHeader.startsWith('Bearer ')) {
      return res.json({ authenticated: false });
    }

    // Dynamically import verifyToken logic
    const jwt = await import('jsonwebtoken');
    const token = authHeader.split(' ')[1];
    try {
      const decoded = jwt.default.verify(token, process.env.JWT_SECRET || 'consultify-secret') as any;
      return res.json({
        authenticated: true,
        userId: decoded.userId || decoded.id,
        userName: decoded.name || decoded.email,
      });
    } catch {
      return res.json({ authenticated: false });
    }
  } catch {
    return res.json({ authenticated: false });
  }
});

/**
 * POST /api/public/report/:token/verify-password
 * Verify password for a protected shared report
 */
router.post('/:token/verify-password', async (req: Request, res: Response, next: NextFunction) => {
  try {
    const tokenParam = req.params.token;
    const token = Array.isArray(tokenParam) ? tokenParam[0] : tokenParam;
    const { password } = req.body;

    // Get link without incrementing view count
    const { getDatabase } = await import('../database/index.js');
    const db = getDatabase();

    const linkRow = await new Promise<any>((resolve, reject) => {
      db.get(
        `SELECT * FROM report_public_links WHERE link_token = ? AND revoked_at IS NULL`,
        [token],
        (err: Error | null, row: any) => {
          if (err) reject(err);
          else resolve(row);
        }
      );
    });

    if (!linkRow) {
      return res.status(404).json({ error: 'Link not found' });
    }

    // Check expiration
    if (linkRow.expires_at && new Date(linkRow.expires_at) < new Date()) {
      return res.status(404).json({ error: 'Link expired' });
    }

    // If no password required
    if (!linkRow.password_hash) {
      return res.json({ valid: true, requiresPassword: false });
    }

    // Verify password
    if (!password || typeof password !== 'string') {
      return res.json({ valid: false, requiresPassword: true });
    }

    const passwordValid = await bcrypt.compare(password, linkRow.password_hash);
    res.json({ valid: passwordValid, requiresPassword: true });
  } catch (err) {
    logger.error('[ReportBuilderPublic] Error verifying password:', err);
    next(err);
  }
});

