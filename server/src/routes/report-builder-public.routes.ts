/**
 * GET /api/public/report/:token
 * Access a shared report via public link (no auth required)
 */
router.get('/:token', async (req: Request, res: Response, next: NextFunction) => {
  try {
    const tokenParam = req.params.token;
    const token = Array.isArray(tokenParam) ? tokenParam[0] : tokenParam;
    const { password } = req.query;

    const result = await ReportBuilderService.getPublicLinkByToken(token);

    if (!result) {
      return res.status(404).json({ error: 'Link not found or expired' });
    }

    // Check password if required
    if (result.link.passwordHash) {
      if (!password || typeof password !== 'string') {
        return res.status(401).json({ error: 'Password required', requiresPassword: true });
      }

      const passwordValid = await bcrypt.compare(password, result.link.passwordHash);
      if (!passwordValid) {
        return res.status(401).json({ error: 'Invalid password', requiresPassword: true });
      }
    }

    // Return enriched report data for public view
    const reportConfig = typeof result.report.config === 'string'
      ? JSON.parse(result.report.config)
      : (result.report.config || {});

    res.json({
      report: {
        id: result.report.id,
        title: result.report.title,
        description: (result.report as any).description,
        sourceName: result.report.sourceName,
        sourceFramework: result.report.sourceFramework,
        status: result.report.status,
        createdAt: result.report.createdAt,
        config: {
          intent: reportConfig.intent || {},
          styling: reportConfig.styling || {},
          language: reportConfig.language,
          chapters: reportConfig.chapters || [],
        },
      },
      sections: result.sections
        .filter((s) => s.enabled)
        .sort((a, b) => a.orderIndex - b.orderIndex)
        .map((s) => ({
          sectionKey: s.sectionKey,
          sectionType: s.sectionType,
          title: s.title,
          content: s.editedContent || s.generatedContent || '',
          renderKind: s.renderKind,
          blockTypeId: (s as any).blockTypeId,
          blockConfig: typeof (s as any).blockConfig === 'string'
            ? JSON.parse((s as any).blockConfig || '{}')
            : ((s as any).blockConfig || {}),
          contentFormat: (s as any).contentFormat,
          orderIndex: s.orderIndex,
          chapter: (s as any).chapter,
        })),
      branding: {
        showCompanyLogo: result.link.showCompanyLogo,
        showConsultinityBranding: result.link.showConsultinityBranding,
        customMessage: result.link.customMessage,
      },
    });
  } catch (err) {
    logger.error('[ReportBuilderPublic] Error accessing public link:', err);
    next(err);
  }
});

/**
 * GET /api/public/report/:token/pdf
 * Download PDF of a shared report (no auth required)
 */
router.get('/:token/pdf', async (req: Request, res: Response, next: NextFunction) => {
  try {
    const tokenParam = req.params.token;
    const token = Array.isArray(tokenParam) ? tokenParam[0] : tokenParam;
    const { password } = req.query;

    const result = await ReportBuilderService.getPublicLinkByToken(token);

    if (!result) {
      return res.status(404).json({ error: 'Link not found or expired' });
    }

    // Check password if required
    if (result.link.passwordHash) {
      if (!password || typeof password !== 'string') {
        return res.status(401).json({ error: 'Password required', requiresPassword: true });
      }

      const passwordValid = await bcrypt.compare(password, result.link.passwordHash);
      if (!passwordValid) {
        return res.status(401).json({ error: 'Invalid password', requiresPassword: true });
      }
    }

    // Generate PDF
    const exportDir = await ensureExportDir();
    const fileName = `public-${token}-${Date.now()}.pdf`;
    const filePath = path.join(exportDir, fileName);

    const enabledSections = result.sections
      .filter((s) => s.enabled)
      .sort((a, b) => a.orderIndex - b.orderIndex);

    await writePublicReportPdf(
      result.report,
      enabledSections,
      {
        showCompanyLogo: result.link.showCompanyLogo,
        showConsultinityBranding: result.link.showConsultinityBranding,
        customMessage: result.link.customMessage,
      },
      filePath
    );

    logger.info('[ReportBuilderPublic] PDF downloaded via public link', {
      reportId: result.report.id,
      token,
    });

    res.setHeader('Content-Type', 'application/pdf');
    res.setHeader(
      'Content-Disposition',
      `attachment; filename="${result.report.title || 'report'}.pdf"`
    );
    return res.sendFile(filePath);
  } catch (err: any) {
    logger.error('[ReportBuilderPublic] Error downloading public PDF:', err);
    return res.status(500).json({ error: 'Failed to generate PDF', message: err.message });
  }
});

/**
 * GET /api/public/report/:token/pptx
 * Download PPTX of a shared report (requires authentication).
 */
router.get('/:token/pptx', async (req: Request, res: Response, next: NextFunction) => {
  try {
    const tokenParam = req.params.token;
    const linkToken = Array.isArray(tokenParam) ? tokenParam[0] : tokenParam;
    const { password: pwd } = req.query;

    // Verify authentication
    const authHeader = req.headers.authorization;
    if (!authHeader || !authHeader.startsWith('Bearer ')) {
      return res.status(401).json({ error: 'Authentication required for PPTX download' });
    }

    const result = await ReportBuilderService.getPublicLinkByToken(linkToken);
    if (!result) {
      return res.status(404).json({ error: 'Link not found or expired' });
    }

    // Check password if required
    if (result.link.passwordHash) {
      if (!pwd || typeof pwd !== 'string') {
        return res.status(401).json({ error: 'Password required', requiresPassword: true });
      }
      const passwordValid = await bcrypt.compare(pwd, result.link.passwordHash);
      if (!passwordValid) {
        return res.status(401).json({ error: 'Invalid password', requiresPassword: true });
      }
    }

    // Generate PPTX using the pipeline
    const { PptxPipelineService } = await import('../services/report/pptx/PptxPipelineService.js');
    const pipeline = new PptxPipelineService();

    const enabledSections = result.sections
      .filter((s) => s.enabled)
      .sort((a, b) => a.orderIndex - b.orderIndex);

    const reportConfig = typeof result.report.config === 'string'
      ? JSON.parse(result.report.config)
      : (result.report.config || {});

    const pptxResult = await pipeline.generateFromLegacyReport(
      {
        report: result.report,
        sections: enabledSections,
        scoreSummary: undefined,
        organizationName: reportConfig.organizationName,
        projectName: result.report.title,
      },
      {
        language: reportConfig.language || 'pl',
        template: reportConfig.styling?.template || 'corporate',
        brandColor: reportConfig.styling?.primaryColor,
        confidentiality: 'confidential',
        addCover: true,
      }
    );

    logger.info('[ReportBuilderPublic] PPTX downloaded via public link', {
      reportId: result.report.id,
      token: linkToken,
      slides: pptxResult.slideCount,
    });

    res.setHeader('Content-Type', 'application/vnd.openxmlformats-officedocument.presentationml.presentation');
    res.setHeader(
      'Content-Disposition',
      `attachment; filename="${result.report.title || 'report'}.pptx"`
    );
    return res.send(pptxResult.buffer);
  } catch (err: any) {
    logger.error('[ReportBuilderPublic] Error downloading public PPTX:', err);
    return res.status(500).json({ error: 'Failed to generate PPTX', message: err.message });
  }
});

